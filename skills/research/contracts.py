# -*- encoding: utf-8 -*-
"""
skills.research contract layer — shared data structures of the research production line
(single source of truth)

All data exchange between the three stages flows through the dataclasses in this module;
task modules only import them, never redefine. The contract is maintained exclusively by
task T01 (tweaks require appending a change record in docs/research/tasks/T00).

Three-layer content separation (methodology: docs/research/company_industry_guide.md):
  fact      fact layer: traceable to a data source (Tushare field / annual-report text / filing)
  view      view layer: third-party research-report claims (org+date mandatory, never cited as fact)
  judgment  judgment layer: hypotheses/scenarios generated by this system (verification indicators mandatory)

On-disk layout (output/research/<ts_code>/, one file per shard so parallel tasks never
write the same file):
  facts_tushare.json     produced by T02
  facts_annual_<year>.json  produced by T03
  views_reports.json     produced by T04
  draft.json             produced by T06
  figs/ch*.png           produced by T07
  report_<date>.md       produced by T08
"""
from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

LAYERS = ("fact", "view", "judgment")


# ---------- evidence and views ----------

@dataclass
class Fact:
    """Fact-layer evidence atom: one traceable factual statement (numeric ones must carry value+unit+period)"""
    eid: str                        # globally unique: "T:tushare.revenue.2025A" / "A:2025.mdna.sub3"
    content: str                    # factual statement (self-contained value+unit+period, one sentence)
    source: str                     # trace description: "fin.income.revenue" / "2025年报·管理层讨论·三、经营情况"
    layer: str = "fact"             # always fact
    ts_code: str = ""
    period: str = ""                # "2025A" / "2025Q3" / "2025-12-31"
    value: Optional[float] = None   # value of numeric facts (for plotting/sorting)
    unit: str = ""                  # 100M yuan / % / 10k units (亿元 / % / 万片)
    confidence: float = 1.0         # verbatim quote=1.0; converted/derived=0.9 with the formula noted in source


@dataclass
class View:
    """View layer: research-report claim (paraphrased without changing the caliber); rendering must
    label it with org+date; strictly never cited as a factual sentence"""
    vid: str                        # "R:<report_id>.<seq>"
    statement: str                  # paraphrased claim (one sentence, caliber preserved)
    org: str                        # common Chinese org name (normalized via core.helpers.normalize_org_name)
    publish_date: str = ""
    report_id: int = 0
    layer: str = "view"             # always view
    ts_code: str = ""
    period: str = ""                # period the claim concerns
    category: str = ""              # viewpoint / forecast / rating / risk


@dataclass
class Hypothesis:
    """Judgment layer: a verifiable research hypothesis (guide requires — hypothesis->indicator->verification loop)"""
    hid: str
    statement: str
    indicators: List[str] = field(default_factory=list)   # verification indicators (with data-source hints)
    related_eids: List[str] = field(default_factory=list)
    status: str = "open"           # open / supported / refuted / needs_review


# ---------- inter-stage exchange artifacts ----------

@dataclass
class EvidenceShard:
    """Evidence shard: one file per data source, each parallel task writes its own; load_pack aggregates them"""
    kind: str                       # tushare / annual / reports
    ts_code: str
    facts: List[Fact] = field(default_factory=list)
    views: List[View] = field(default_factory=list)
    meta: Dict[str, Any] = field(default_factory=dict)    # generated-at / coverage notes / extraction stats


@dataclass
class Chapter:
    """One chapter produced by Stage 2 (chapter order and template in prompts task T05)"""
    no: int                         # 1..10
    title: str
    body_md: str                    # body text; inline citation markers [E:eid] / [V:vid]
    used_eids: List[str] = field(default_factory=list)


@dataclass
class Draft:
    """draft.json — full Stage 2 output"""
    ts_code: str
    name: str
    generated_at: str = ""
    chapters: List[Chapter] = field(default_factory=list)
    hypotheses: List[Hypothesis] = field(default_factory=list)
    flags: List[str] = field(default_factory=list)        # citation-checker warnings (T06)


# ---------- serialization and aggregation ----------

_DC = {"shard": EvidenceShard, "draft": Draft}


def _from(cls, d: Dict[str, Any]):
    """dict -> dataclass (unknown keys ignored; nested lists hydrated recursively)"""
    nested = {"facts": Fact, "views": View, "chapters": Chapter,
              "hypotheses": Hypothesis}
    names = {f.name for f in cls.__dataclass_fields__.values()}  # type: ignore[attr-defined]
    obj = cls(**{k: v for k, v in d.items() if k in names})
    for fname, fcls in nested.items():
        if hasattr(obj, fname):
            setattr(obj, fname, [fcls(**{k: v for k, v in (x if isinstance(x, dict)
                                                            else asdict(x)).items()
                                          if k in {f.name for f in fcls.__dataclass_fields__.values()}})
                                 for x in getattr(obj, fname)])
    return obj


def save_shard(shard: EvidenceShard, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(asdict(shard), ensure_ascii=False, indent=1),
                    encoding="utf-8")


def load_shard(path: Path) -> EvidenceShard:
    return _from(EvidenceShard, json.loads(path.read_text(encoding="utf-8")))


def load_pack(research_dir: Path) -> Tuple[List[Fact], List[View]]:
    """Aggregate all evidence shards in the directory -> (facts, views); duplicate eid/vid keeps the first, later ones ignored"""
    facts: List[Fact] = []
    views: List[View] = []
    seen_f, seen_v = set(), set()
    for p in sorted(research_dir.glob("*.json")):
        if p.name.startswith(("draft", "report")):
            continue
        try:
            shard = load_shard(p)
        except Exception:            # skip non-shard files
            continue
        for f in shard.facts:
            fd = _from(Fact, f if isinstance(f, dict) else asdict(f))
            if fd.eid not in seen_f:
                seen_f.add(fd.eid)
                facts.append(fd)
        for v in shard.views:
            vd = _from(View, v if isinstance(v, dict) else asdict(v))
            if vd.vid not in seen_v:
                seen_v.add(vd.vid)
                views.append(vd)
    return facts, views


def save_draft(draft: Draft, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(asdict(draft), ensure_ascii=False, indent=1),
                    encoding="utf-8")


def load_draft(path: Path) -> Draft:
    return _from(Draft, json.loads(path.read_text(encoding="utf-8")))


def research_dir(root_out: Path, ts_code: str) -> Path:
    """output/research/<ts_code>/"""
    return root_out / "research" / ts_code


# ---------- validation and stats (T01: pure-logic machine checks before a shard/draft enters the next stage) ----------

# Legal period formats: YYYY / YYYYA / YYYYE / YYYYH1 / YYYYQn (n=1-4) / YYYY-MM-DD (real date)
# YYYYE = research-report earnings-forecast estimate period (e.g. 2026E, T04 contract change 2026-09-25)
_PERIOD_RE = re.compile(
    r"^(?:\d{4}|\d{4}A|\d{4}E|\d{4}H1|\d{4}Q[1-4]"
    r"|\d{4}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01]))$"
)
_HAS_DIGIT = re.compile(r"\d")
_CITE_RE = re.compile(r"\[(E|V):([^\]\s]+)\]")   # inline citation [E:eid] / [V:vid]

_FACT_EID_PREFIXES = ("T:", "A:")   # T: Tushare domain / A: annual report
_VIEW_VID_PREFIX = "R:"             # R: research report


def valid_period(period: str) -> bool:
    """Period format is legal: YYYY / YYYYA / YYYYE / YYYYH1 / YYYYQn / YYYY-MM-DD (month/day must be real)"""
    if not _PERIOD_RE.match(period):
        return False
    if len(period) == 10:           # date form: also reject "format-valid but not a real date" like 02-30
        try:
            datetime.strptime(period, "%Y-%m-%d")
        except ValueError:
            return False
    return True


def validate_shard(shard: EvidenceShard) -> List[str]:
    """Validate an evidence shard, returning the error list (empty = valid).

    Rules: eid/vid unique within the shard with legal prefixes (T:/A: for facts,
    R: for views); Fact.layer=="fact"; View.org and publish_date non-empty; period
    (when non-empty) format-legal; content containing digits must have value or unit
    non-empty.
    """
    errors: List[str] = []
    seen_eids: set = set()
    for i, f in enumerate(shard.facts):
        where = f"[{shard.kind}] facts[{i}]"
        if f.eid in seen_eids:
            errors.append(f"{where} eid 重复: {f.eid!r}")
        seen_eids.add(f.eid)
        if not f.eid.startswith(_FACT_EID_PREFIXES):
            errors.append(f"{where} eid 前缀非法: {f.eid!r} (须 T:/A:)")
        if f.layer != "fact":
            errors.append(f"{where} layer 必须为 'fact', 实为 {f.layer!r}")
        if f.period and not valid_period(f.period):
            errors.append(f"{where} period 格式非法: {f.period!r} "
                          f"(合法: YYYY/YYYYA/YYYYE/YYYYH1/YYYYQn/YYYY-MM-DD)")
        if _HAS_DIGIT.search(f.content) and f.value is None and not f.unit:
            errors.append(f"{where} content 含数字但 value 与 unit 均空: {f.eid!r}")
    seen_vids: set = set()
    for i, v in enumerate(shard.views):
        where = f"[{shard.kind}] views[{i}]"
        if v.vid in seen_vids:
            errors.append(f"{where} vid 重复: {v.vid!r}")
        seen_vids.add(v.vid)
        if not v.vid.startswith(_VIEW_VID_PREFIX):
            errors.append(f"{where} vid 前缀非法: {v.vid!r} (须 R:)")
        if not v.org:
            errors.append(f"{where} View.org 为空 (观点必须可归属机构)")
        if not v.publish_date:
            errors.append(f"{where} View.publish_date 为空 (观点必须可定位日期)")
        if v.period and not valid_period(v.period):
            errors.append(f"{where} period 格式非法: {v.period!r} "
                          f"(合法: YYYY/YYYYA/YYYYE/YYYYH1/YYYYQn/YYYY-MM-DD)")
    return errors


def validate_draft(draft: Draft, facts: List[Fact], views: List[View]) -> List[str]:
    """Validate the draft's citation loop: used_eids and inline [E:eid]/[V:vid] in the body
    must exist in the evidence pack; every hypothesis needs >=1 non-empty indicator.
    Returns the error list (empty = valid)."""
    errors: List[str] = []
    eid_set = {f.eid for f in facts}
    vid_set = {v.vid for v in views}
    for ch in draft.chapters:
        where = f"[draft] 第{ch.no}章<{ch.title}>"
        for ref in ch.used_eids:
            if ref.startswith(_FACT_EID_PREFIXES):
                if ref not in eid_set:
                    errors.append(f"{where} used_eids 引用不存在的事实: {ref!r}")
            elif ref.startswith(_VIEW_VID_PREFIX):
                if ref not in vid_set:
                    errors.append(f"{where} used_eids 引用不存在的观点: {ref!r}")
            else:
                errors.append(f"{where} used_eids 前缀非法: {ref!r} (须 T:/A:/R:)")
        for m in _CITE_RE.finditer(ch.body_md):
            pool = eid_set if m.group(1) == "E" else vid_set
            if m.group(2) not in pool:
                errors.append(f"{where} 行内引用 {m.group(0)} 不在证据集")
    for h in draft.hypotheses:
        if not [s for s in h.indicators if s and s.strip()]:
            errors.append(f"[draft] 假设 {h.hid!r} 缺验证指标 (indicators 至少 1 条非空)")
    return errors


def pack_stats(facts: List[Fact], views: List[View]) -> Dict[str, Any]:
    """Evidence-pack stats: by source prefix (T=tushare/A=annual/R=reports), by period, and view-org
    distribution — feeds the T09 scorecard and debugging."""
    def kind_of(ref: str) -> str:
        if ref.startswith("T:"):
            return "tushare"
        if ref.startswith("A:"):
            return "annual"
        if ref.startswith("R:"):
            return "reports"
        return "other"

    def bump(counter: Dict[str, int], key: str) -> None:
        counter[key] = counter.get(key, 0) + 1

    facts_by_kind: Dict[str, int] = {}
    facts_by_period: Dict[str, int] = {}
    for f in facts:
        bump(facts_by_kind, kind_of(f.eid))
        bump(facts_by_period, f.period or "unknown")
    views_by_kind: Dict[str, int] = {}
    views_by_period: Dict[str, int] = {}
    views_by_org: Dict[str, int] = {}
    for v in views:
        bump(views_by_kind, kind_of(v.vid))
        bump(views_by_period, v.period or "unknown")
        bump(views_by_org, v.org or "unknown")
    return {
        "fact_count": len(facts),
        "view_count": len(views),
        "numeric_fact_count": sum(1 for f in facts if f.value is not None),
        "facts_by_kind": facts_by_kind,
        "views_by_kind": views_by_kind,
        # org coverage distribution (view diversity for the scorecard): count desc, then name asc
        "views_by_org": dict(sorted(views_by_org.items(), key=lambda kv: (-kv[1], kv[0]))),
        "facts_by_period": dict(sorted(facts_by_period.items())),
        "views_by_period": dict(sorted(views_by_period.items())),
    }
