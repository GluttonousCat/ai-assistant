def _rule_based_sql(user_input: str) -> Optional[str]:
    """
    Rule-template SQL generation: supports preset query patterns only
    Flow: identify the metric name first -> extract the stock name backwards -> pick the data source by metric type
    """
    text = user_input.strip()

    # 0. Preprocess: cut the second metric joined by "和/与" (rules support a single
    #    metric only); only when "和/与" appears after the metric (dual-metric case), keep the first

    # 1. Locate the metric position (search the text by metric keywords)
    metric_pos = None
    matched_metric = None
    for metric_kw in sorted(METRIC_ALIAS.keys(), key=len, reverse=True):
        idx = text.find(metric_kw)
        if idx >= 0:
            metric_pos = idx
            matched_metric = metric_kw
            break

    if metric_pos is None:
        return None

    # 2. Extract the stock name (text before the metric, strip action words/years/time words/"的")
    prefix = text[:metric_pos]
    # longer verb alternatives first, so '查一下' is not eaten by '查'
    prefix = re.sub(
        r"(?:查一下|查一查|查询|帮我查一下|帮我查|请问|看看|查看|请查|帮我|请|查|看|"
        r"的|、|和|与|最近|最新|近|\\s+)",
        "", prefix,
    )
    # strip years and time ranges (2020年 / 2020 年 / 最近两年 / 前三年)
    prefix = re.sub(r"\d{4}\s*年", "", prefix)
    prefix = re.sub(r"最近|最近一年|最近两年|最近三年|近一年|近两年|近三年|今年以来", "", prefix)
    # strip leftover filler words at the start
    prefix = re.sub(r"^(查询结果|请|帮我|一下)", "", prefix).strip()
    if not prefix:
        return None
    stock = prefix
    ts_code = lookup_ts_code(stock)
    if not ts_code:
        return None

    field, source = _match_metric_field(matched_metric)
    if not field:
        return None

    # 3. Generate SQL by data source
    if source == "market":
        # Quote data: daily + daily_basic (latest trading day)
        return f"""SELECT d.trade_date, s.name AS stock_name, d.close, d.open, d.high, d.low,
       d.vol, d.amount, d.pct_chg, db.pe_ttm, db.pb, db.total_mv, db.circ_mv
FROM stock.daily d
JOIN stock.stock_basic s ON d.ts_code = s.ts_code
LEFT JOIN stock.daily_basic db
    ON d.trade_date = db.trade_date AND d.ts_code = db.ts_code
WHERE d.ts_code = '{ts_code}'
ORDER BY d.trade_date DESC
LIMIT 8"""

    # Financial data: income + fina_indicator (consolidated statements); no internal ts_code column
    return f"""SELECT s.name AS stock_name, i.end_date, {field}
FROM fin.income i
JOIN stock.stock_basic s ON i.ts_code = s.ts_code
LEFT JOIN fin.fina_indicator f
    ON i.ts_code = f.ts_code AND i.end_date = f.end_date AND i.report_type = f.report_type
WHERE i.ts_code = '{ts_code}' AND i.report_type = '1'
ORDER BY i.end_date DESC
LIMIT 48"""


def _match_metric_field(metric: str) -> tuple[Optional[str], str]:
    """
    Map a metric name to (database field, data source type)
    source: 'financial' (three statements + indicators) / 'market' (quotes + valuation)
    """
    m = metric.lower()
    # exact alias match (carries the data source tag)
    for key, entry in METRIC_ALIAS_FULL.items():
        if m == key.lower() or m in key.lower():
            return entry["field"], entry["source"]

    # keyword mapping
    for key, (prefix, field, source) in TABLE_FIELD_MAP.items():
        if key in m:
            return f"{prefix}.{field}", source
    return None, "financial"


