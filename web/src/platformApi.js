import { auth, authorizedFetch, request, sseStream } from './lib/http.js'

export { auth }

export const platformApi = {
  quantWorkspace: (options) => request('GET', '/api/v1/quant/workspace', undefined, options),
  quantAvailability: (options) => request('GET', '/api/v1/quant/workspace/availability', undefined, options),
  quantSaveDraft: (draft) => request('POST', '/api/v1/quant/workspace/drafts', draft),
  quantGenerate: (body) => request('POST', '/api/v1/quant/workspace/generate', body),
  quantSubmit: (body) => request('POST', '/api/v1/quant/workspace/tasks', body),
  quantWorkspaceResult: (taskId, offset = 0, limit = 30) => request('GET', `/api/v1/quant/workspace/tasks/${encodeURIComponent(taskId)}/result?${new URLSearchParams({ offset, limit })}`),
  quantStrategies: () => request('GET', '/api/v1/quant/strategies'),
  quantBacktests: () => request('GET', '/api/v1/quant/backtests?limit=100'),
  quantBacktest: (runId, offset = 0, limit = 30) => request('GET', `/api/v1/quant/backtests/${encodeURIComponent(runId)}?${new URLSearchParams({offset, limit})}`),
  marketDashboard: () => request('GET', '/api/v1/market/dashboard'),
  marketFreshness: () => request('GET', '/api/v1/market/freshness'),
  marketIntraday: (options = {}) => request('GET', '/api/v1/market/intraday', undefined, options),
  marketIntradayChart: (code, runId, timeframe = '60F', options = {}) => request('GET', `/api/v1/market/intraday/${encodeURIComponent(code)}?${new URLSearchParams({ run_id: runId, timeframe })}`, undefined, options),
  marketTracking: (date, options = {}) => request('GET', `/api/v1/market/tracking${date ? `?signal_date=${encodeURIComponent(date)}` : ''}`, undefined, options),
  marketTrackingEpisodes: (view = 'active', options = {}) => request('GET', `/api/v1/market/tracking/episodes?${new URLSearchParams({ view })}`, undefined, options),
  marketTrackingChart: (code, runId, timeframe = '1D', options = {}) => request('GET', `/api/v1/market/tracking/${encodeURIComponent(code)}?${new URLSearchParams({ run_id: runId, timeframe })}`, undefined, options),
  marketStock: (code, runId, timeframe = '60F', options = {}) => request('GET', `/api/v1/market/dashboard/${encodeURIComponent(code)}?${new URLSearchParams({timeframe, ...(runId ? {run_id: runId} : {})})}`, undefined, options),
  login: (username, password) =>
    request('POST', '/api/auth/login', { username, password }),
  register: (username, password, inviteCode) =>
    request('POST', '/api/auth/register', {
      username, password, invite_code: inviteCode,
    }),
  me: () => request('GET', '/api/auth/me'),
  listUsers: () => request('GET', '/api/auth/users'),
  setUserRole: (userId, role) =>
    request('POST', `/api/auth/users/${userId}/role`, { role }),

  // Agent chat endpoint (LLM autonomous decisions + tool loop): free-form questions + multi-turn follow-ups.
  // session_id is generated by the page and carried throughout; the server injects session history from it
  // (follow-ups may omit the subject and still resolve)
  agentStream: async (text, sessionId, onEvent) =>
    sseStream('/api/v1/agent/stream', { text, session_id: sessionId }, onEvent).promise,
  agentStreamRaw: (text, sessionId, onEvent) =>
    sseStream('/api/v1/agent/stream', { text, session_id: sessionId }, onEvent),

  // Chain page (beta_alpha): chain list + per-chain quant analysis (no LLM)
  chains: () => request('GET', '/api/v1/chains'),
  chainAnalysis: (chainId, node) =>
    request('GET', `/api/v1/chains/${chainId}/analysis${node ? `?node=${encodeURIComponent(node)}` : ''}`),
  // Seed chain forging: SSE (stage data{yaml,report,chain_id} done); returns {promise, abort}
  forgeChainRaw: (theme, onEvent) => sseStream('/api/v1/chains/forge/stream', { theme }, onEvent),
  // Save seed chain (server-side structure validation)
  saveChain: (yamlText) => request('POST', '/api/v1/chains/save', { yaml: yamlText }),

  // Reports center
  reports: (params = {}, options = {}) => {
    const qs = new URLSearchParams(
      Object.entries(params).filter(([, v]) => v !== undefined && v !== null && v !== '')
    ).toString()
    return request('GET', `/api/reports${qs ? `?${qs}` : ''}`, undefined, options)
  },
  reportTags: () => request('GET', '/api/reports/tags'),
  reportStocks: () => request('GET', '/api/reports/stocks'),
  reportDetail: (id, options = {}) => request('GET', `/api/reports/${id}`, undefined, options),
  // Download the original report (authorized fetch blob -> browser save; returns the saved filename)
  downloadReport: async (id) => {
    const res = await authorizedFetch(`/api/reports/${id}/download`)
    const blob = await res.blob()
    // content-disposition: attachment; filename*=UTF-8''<urlencoded>
    const cd = res.headers.get('content-disposition') || ''
    const m = cd.match(/filename\*=UTF-8''([^;]+)/)
    const name = m ? decodeURIComponent(m[1]) : `report_${id}.pdf`
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = name
    document.body.appendChild(a)
    a.click()
    a.remove()
    URL.revokeObjectURL(url)
    return name
  },
  analyzeReport: (id) => request('POST', `/api/reports/${id}/analyze`),
  // Single-report AI analysis, streaming version (SSE): events are isomorphic with chatStream
  //   {type:'stage', stage, message} {type:'delta', text} {type:'data', data} {type:'error'|'done'}
  // Returns {promise, abort}: closing the modal calls abort() to drop the connection (backend analysis still completes ingestion)
  analyzeReportStream: (id, onEvent) =>
    sseStream(`/api/reports/${id}/analyze/stream`, {}, onEvent),

  // Workbench overview
  health: () => request('GET', '/health'),

  // Real-time monitor (adminOnly): one SSE frame every 2s {state:{metrics,pg}}; returns {promise, abort}
  monitorStream: (onEvent) => sseStream('/api/monitor/stream', {}, onEvent),
  monitorState: () => request('GET', '/api/monitor/state'),
}
