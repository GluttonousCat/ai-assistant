// Platform API client (JWT-authenticated)
const TOKEN_KEY = 'aiass_token'
const USER_KEY = 'aiass_user'

export const auth = {
  getToken: () => localStorage.getItem(TOKEN_KEY) || '',
  getUser: () => {
    try { return JSON.parse(localStorage.getItem(USER_KEY) || 'null') } catch { return null }
  },
  save(token, user) {
    localStorage.setItem(TOKEN_KEY, token)
    localStorage.setItem(USER_KEY, JSON.stringify(user))
  },
  clear() {
    localStorage.removeItem(TOKEN_KEY)
    localStorage.removeItem(USER_KEY)
  },
}

async function request(method, path, body) {
  const headers = { 'Content-Type': 'application/json' }
  const token = auth.getToken()
  if (token) headers['Authorization'] = `Bearer ${token}`
  const res = await fetch(path, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  // 401: on the login endpoint a 401 means "wrong password"; on other endpoints it means "session expired"
  if (res.status === 401 && !path.startsWith('/api/auth/login')) {
    auth.clear()
    window.dispatchEvent(new CustomEvent('auth:expired'))
    throw new Error('登录已失效, 请重新登录')
  }
  if (!res.ok) {
    const data = await res.json().catch(() => ({}))
    throw new Error(data.detail || `HTTP ${res.status}`)
  }
  return res.json()
}

// Streaming SSE POST: invokes onEvent({type, ...}) per event.
// Returns {promise, abort} immediately: promise resolves when the stream ends/fails; abort() can interrupt at any time.
function sseStream(path, body, onEvent) {
  const ac = new AbortController()
  const promise = (async () => {
    const res = await fetch(path, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${auth.getToken()}` },
      body: JSON.stringify(body),
      signal: ac.signal,
    })
    if (res.status === 401) {
      auth.clear()
      window.dispatchEvent(new CustomEvent('auth:expired'))
      throw new Error('登录已失效, 请重新登录')
    }
    if (!res.ok) {
      const errBody = await res.json().catch(() => ({}))
      throw new Error(errBody.detail || `HTTP ${res.status}`)
    }
    const reader = res.body.getReader()
    const decoder = new TextDecoder('utf-8')
    let buf = ''
    try {
      for (;;) {
        const { done, value } = await reader.read()
        if (done) break
        buf += decoder.decode(value, { stream: true })
        // SSE events are separated by blank lines
        const parts = buf.split('\n\n')
        buf = parts.pop()
        for (const part of parts) {
          let event = 'message'
          let data = ''
          for (const line of part.split('\n')) {
            if (line.startsWith('event: ')) event = line.slice(7).trim()
            else if (line.startsWith('data: ')) data += line.slice(6)
          }
          if (!data) continue
          let payload
          try { payload = JSON.parse(data) } catch { payload = { text: data } }
          onEvent({ type: event, ...payload })
        }
      }
    } catch (err) {
      if (err.name !== 'AbortError') throw err
    } finally {
      reader.releaseLock?.()
    }
  })()
  return { promise, abort: () => ac.abort() }
}

export const platformApi = {
  login: (username, password) =>
    request('POST', '/api/auth/login', { username, password }),
  register: (username, password, inviteCode) =>
    request('POST', '/api/auth/register', {
      username, password, invite_code: inviteCode,
    }),
  me: () => request('GET', '/api/auth/me'),
  listUsers: () => request('GET', '/api/auth/users'),
  setUserRole: (userId, role) =>
    request('POST', `/api/auth/users/${userId}/role`, { role }),

  // Agent chat endpoint (LLM autonomous decisions + tool loop): free-form questions + multi-turn follow-ups.
  // session_id is generated by the page and carried throughout; the server injects session history from it
  // (follow-ups may omit the subject and still resolve)
  agentStream: async (text, sessionId, onEvent) => {
    await sseStream('/api/v1/agent/stream', { text, session_id: sessionId }, onEvent).promise
  },

  // Chain page (beta_alpha): chain list + per-chain quant analysis (no LLM)
  chains: () => request('GET', '/api/v1/chains'),
  chainAnalysis: (chainId, node) =>
    request('GET', `/api/v1/chains/${chainId}/analysis${node ? `?node=${encodeURIComponent(node)}` : ''}`),
  // Seed chain forging: SSE (stage data{yaml,report,chain_id} done); returns {promise, abort}
  forgeChainRaw: (theme, onEvent) => sseStream('/api/v1/chains/forge/stream', { theme }, onEvent),
  // Save seed chain (server-side structure validation)
  saveChain: (yamlText) => request('POST', '/api/v1/chains/save', { yaml: yamlText }),

  // Reports center
  reports: (params = {}) => {
    const qs = new URLSearchParams(
      Object.entries(params).filter(([, v]) => v !== undefined && v !== null && v !== '')
    ).toString()
    return request('GET', `/api/reports${qs ? `?${qs}` : ''}`)
  },
  reportTags: () => request('GET', '/api/reports/tags'),
  reportStocks: () => request('GET', '/api/reports/stocks'),
  reportDetail: (id) => request('GET', `/api/reports/${id}`),
  // Download the original report (authorized fetch blob -> browser save; returns the saved filename)
  downloadReport: async (id) => {
    const res = await fetch(`/api/reports/${id}/download`, {
      headers: { Authorization: `Bearer ${auth.getToken()}` },
    })
    if (res.status === 401) {
      auth.clear()
      window.dispatchEvent(new CustomEvent('auth:expired'))
      throw new Error('登录已失效, 请重新登录')
    }
    if (!res.ok) {
      const body = await res.json().catch(() => ({}))
      throw new Error(body.detail || `HTTP ${res.status}`)
    }
    const blob = await res.blob()
    // content-disposition: attachment; filename*=UTF-8''<urlencoded>
    const cd = res.headers.get('content-disposition') || ''
    const m = cd.match(/filename\*=UTF-8''([^;]+)/)
    const name = m ? decodeURIComponent(m[1]) : `report_${id}.pdf`
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = name
    document.body.appendChild(a)
    a.click()
    a.remove()
    URL.revokeObjectURL(url)
    return name
  },
  analyzeReport: (id) => request('POST', `/api/reports/${id}/analyze`),
  // Single-report AI analysis, streaming version (SSE): events are isomorphic with chatStream
  //   {type:'stage', stage, message} {type:'delta', text} {type:'data', data} {type:'error'|'done'}
  // Returns {promise, abort}: closing the modal calls abort() to drop the connection (backend analysis still completes ingestion)
  analyzeReportStream: (id, onEvent) =>
    sseStream(`/api/reports/${id}/analyze/stream`, {}, onEvent),

  // Workbench overview
  health: () => request('GET', '/health'),

  // Real-time monitor (adminOnly): one SSE frame every 2s {state:{metrics,pg}}; returns {promise, abort}
  monitorStream: (onEvent) => sseStream('/api/monitor/stream', {}, onEvent),
  monitorState: () => request('GET', '/api/monitor/state'),
}
