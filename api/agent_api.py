"""Authenticated Agent SSE entry point."""
from __future__ import annotations
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from api.events import sse as _sse
from api.deps import get_current_user
from api.schemas import AgentChatRequest
from core.security import TokenPayload

fin_router = APIRouter(prefix="/api/v1", tags=["agent"])

@fin_router.post("/agent/stream")
async def agent_stream_endpoint(request: AgentChatRequest,
                                current: TokenPayload = Depends(get_current_user)):
    """Agent chat SSE (free-form questions + multi-turn follow-ups)

    Request: {text, session_id} — session_id is generated by the frontend and
    carried throughout (multi-turn context)
    Events: stage / tool_call / data(intent=agent) / delta / done / error
    Sandbox: registered read-only tools, per-tool timeout, round limit (see harness/loop.py)
    """
    text = request.text
    # Client IDs are scoped by the authenticated identity; guessing another ID
    # must never expose another user's history, stock slots or trajectory.
    session_id = f"user-{current.user_id}-{request.session_id}" if request.session_id else None

    async def gen():
        from harness.loop import run_agent_stream
        # HTTP SSE is independent of stdout. Process-wide redirection across
        # awaits would interfere with concurrent requests and background jobs.
        try:
            async for chunk in run_agent_stream(text, session_id, _sse):
                yield chunk
        except Exception as e:  # noqa: BLE001
            yield _sse("error", {"message": f"Agent 执行失败: {e}"})
        yield _sse("done", {})

    return StreamingResponse(
        gen(), media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})
